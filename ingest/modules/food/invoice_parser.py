"""
Parse Swiggy / Toing food-order TAX INVOICE PDFs.

Both Swiggy (noreply@swiggy.in) and Toing (notify@toingit.com) invoices are
generated by the same "Swiggy Limited" GST invoicing backend, so a single
parser handles both. Platform attribution comes from the email sender, not the
PDF.

Uses pdfplumber's layout-aware text extraction, which aligns the invoice's
label/value columns cleanly (unlike naive text extraction).
"""
import re

import pdfplumber

# Fee/charge line-items that are not actual food (excluded from the item list,
# still reflected in the invoice total).
_FEE_RE = re.compile(
    r"packing charge|delivery (?:fee|charge|partner)|convenience fee|platform fee|handling",
    re.IGNORECASE,
)

# Item row, e.g. (columns: Sr Description OTH Qty UnitPrice Amount Discount ...):
#   "1.  Dhaba Chicken  OTH  1  510.00  510.00  0.00  510.00"
#   "2.  Juicy Lucy Lamb Burger + Fries  OTH  1  415.00  415.00  20.09  394.91"
_ITEM_RE = re.compile(
    r"^\s*\d+\.\s+(?P<name>.+?)\s+OTH\s+(?P<qty>\d+)?\s*"
    r"(?P<unit>[\d,]+\.\d{2})\s+(?P<amount>[\d,]+\.\d{2})\s+(?P<disc>[\d,]+\.\d{2})"
)

_TEMPLATE_MARKER = "Invoice issued by Swiggy Limited"


def _num(s):
    return float(s.replace(",", ""))


def _iso_date(dmy):
    """Convert DD-MM-YYYY -> YYYY-MM-DD; return None on malformed input."""
    m = re.match(r"^(\d{2})-(\d{2})-(\d{4})$", dmy or "")
    if not m:
        return None
    d, mo, y = m.groups()
    return f"{y}-{mo}-{d}"


def parse_food_invoice(pdf_path, order_id_hint=None):
    """
    Parse a Swiggy/Toing food invoice PDF.

    Returns a dict:
        {order_id, restaurant, order_date, total, items: [{name, qty, amount, is_fee}]}
    or None if the PDF is not a recognizable Swiggy/Toing food invoice.
    """
    try:
        with pdfplumber.open(pdf_path) as pdf:
            text = "\n".join((pg.extract_text(layout=True) or "") for pg in pdf.pages)
    except Exception:
        return None

    # Signature check — must be the Swiggy Limited restaurant-invoice template.
    if _TEMPLATE_MARKER not in text or "Restaurant Name:" not in text:
        return None

    lines = text.split("\n")

    restaurant = None
    for ln in lines:
        m = re.search(r"Restaurant Name:\s+(.+?)\s*$", ln)
        if m:
            restaurant = m.group(1).strip()
            break

    order_id = None
    m = re.search(r"Order ID:\s+(\d{6,})", text)
    if m:
        order_id = m.group(1)
    if not order_id and order_id_hint:
        order_id = str(order_id_hint)

    order_date = None
    m = re.search(r"Date of Invoice:\s+(\d{2}-\d{2}-\d{4})", text)
    if m:
        order_date = _iso_date(m.group(1))

    total = None
    m = re.search(r"Invoice Total\s+([\d,]+\.\d{2})", text)
    if m:
        total = _num(m.group(1))

    items = []
    for ln in lines:
        m = _ITEM_RE.match(ln)
        if not m:
            continue
        name = m.group("name").strip()
        items.append(
            {
                "name": name,
                "qty": int(m.group("qty")) if m.group("qty") else 1,
                "amount": _num(m.group("amount")),
                "is_fee": bool(_FEE_RE.search(name)),
            }
        )

    # Require the essentials, and at least one real (non-fee) food item.
    if not restaurant or not any(not it["is_fee"] for it in items):
        return None

    return {
        "order_id": order_id,
        "restaurant": restaurant,
        "order_date": order_date,
        "total": total,
        "items": items,
    }
